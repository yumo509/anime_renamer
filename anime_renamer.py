    def has_video_files(self, folder_path: Path, deep: bool = True) -> bool:
        """检查文件夹中是否包含视频文件"""
        if not folder_path.is_dir():
            return False
        
        if deep:
            for root, dirs, files in os.walk(folder_path):
                for f in files:
                    if is_video_file(f):
                        return True
        else:
            for f in folder_path.iterdir():
                if f.is_file() and is_video_file(f.name):
                    return True
        
        return False
    
    def is_single_episode_folder(self, folder_path: Path) -> bool:
        """判断是否为单集文件夹"""
        if not folder_path.is_dir():
            return False
        
        video_files = [f for f in folder_path.iterdir() if f.is_file() and is_video_file(f.name)]
        
        # 只有1个视频文件，很可能是单集文件夹
        if len(video_files) == 1:
            return True
        
        # 文件夹名包含集数模式（如 "动漫名 - 01"）
        folder_name = folder_path.name
        if re.search(r'[-–—]\s*\d{1,3}\b', folder_name):
            return True
        
        # 包含数字且视频文件很少（<=3）
        if len(video_files) <= 3 and re.search(r'\d{1,3}', folder_name):
            return True
        
        return False
    
    def extract_base_anime_name(self, folder_name: str) -> str:
        """从单集文件夹名中提取基础动漫名称"""
        name = folder_name
        
        # 去掉集数部分
        # 模式1：动漫名 - 集数
        match = re.search(r'^(.*?)\s*[-–—]\s*\d{1,3}', name)
        if match:
            base = match.group(1).strip()
            if base:
                return clean_name(base)
        
        # 模式2：动漫名 集数（v2.1.7: 去掉长度限制，让MAO这类短名称也能正确提取）
        match = re.search(r'^(.*?)\s+\d{1,3}\b', name)
        if match:
            base = match.group(1).strip()
            if base and len(base) >= 1:
                return clean_name(base)
        
        # 模式3：动漫名 SxxExx
        match = re.search(r'^(.*?)\s*S\d{1,2}E\d{1,3}', name, re.IGNORECASE)
        if match:
            base = match.group(1).strip()
            if base:
                return clean_name(base)
        
        return clean_name(name)
    
    def merge_single_episode_folders(self):
        """智能合并同一系列的单集文件夹"""
        print("\n" + "=" * 60)
        print("正在扫描并合并单集文件夹...")
        print("=" * 60)
        
        if not self.root_path.is_dir():
            print(f"错误：路径不存在 - {self.root_path}")
            return
        
        # 收集所有一级子文件夹
        subfolders = [f for f in self.root_path.iterdir() if f.is_dir()]
        
        # 筛选单集文件夹
        single_ep_folders = []
        for folder in subfolders:
            if self.is_single_episode_folder(folder):
                base_name = self.extract_base_anime_name(folder.name)
                if base_name and base_name != "未命名动漫":
                    single_ep_folders.append((folder, base_name))
        
        if not single_ep_folders:
            print("  未发现需要合并的单集文件夹")
            return
        
        # 按基础名称分组
        groups: Dict[str, List[Path]] = {}
        for folder, base_name in single_ep_folders:
            # 模糊匹配相似的名称
            matched = False
            for key in groups.keys():
                if calculate_similarity(base_name, key) > 0.8:
                    groups[key].append(folder)
                    matched = True
                    break
            if not matched:
                groups[base_name] = [folder]
        
        # 合并每组
        for base_name, folders in groups.items():
            if len(folders) < 2:
                continue  # 只有一个的话不需要合并
            
            print(f"\n  合并: {len(folders)} 个单集文件夹 -> {base_name}/")
            
            # 目标文件夹
            target_folder = self.root_path / base_name
            
            if not self.dry_run:
                target_folder.mkdir(exist_ok=True)
            
            # 移动每个文件夹的内容
            for folder in folders:
                try:
                    # 移动所有文件
                    for item in folder.iterdir():
                        src = item
                        dst = target_folder / item.name
                        
                        # 如果目标已存在，重命名
                        if dst.exists():
                            stem = dst.stem
                            suffix = dst.suffix
                            counter = 1
                            while dst.exists():
                                dst = target_folder / f"{stem}_{counter}{suffix}"
                                counter += 1
                        
                        if not self.dry_run:
                            src.rename(dst)
                        
                        self.changes.append(f"移动文件: {folder.name}/{item.name} -> {base_name}/{dst.name}")
                    
                    # 删除空文件夹
                    if not self.dry_run:
                        try:
                            folder.rmdir()
                        except:
                            pass  # 文件夹可能不为空
                    
                    self.merged_folders += 1
                    
                except Exception as e:
                    print(f"    [!] 合并 {folder.name} 时出错: {e}")
                    self.errors += 1
        
        print(f"\n  共合并了 {self.merged_folders} 个单集文件夹")
    
    def process_anime_folder(self, anime_path: Path):
        """处理单个动漫文件夹"""
        folder_name = anime_path.name
        
        # 检查是否有视频文件
        if not self.has_video_files(anime_path):
            print(f"  跳过: {folder_name}（无视频文件）")
