def calculate_similarity(str1: str, str2: str) -> float:
    """计算两个字符串的相似度（0-1）"""
    # 先转小写
    str1 = str1.lower()
    str2 = str2.lower()
    
    # 使用 difflib 计算相似度
    return difflib.SequenceMatcher(None, str1, str2).ratio()


