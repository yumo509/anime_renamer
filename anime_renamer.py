class BangumiClient:
    """Bangumi API 客户端（国内动漫数据库）"""
    
    def __init__(self, proxy: str = ""):
        self.base_url = BANGUMI_BASE_URL
        self.session = requests.Session()
        self.session.headers.update({
            "User-Agent": "AnimeRenamer/1.8 (https://github.com/example/anime-renamer)",
            "Accept": "application/json"
        })
        
        # 设置代理
        if proxy:
            self.session.proxies = {
                "http": proxy,
                "https": proxy
            }
    
    def _make_request(self, url: str, params: dict = None) -> Optional[dict]:
        """带重试机制的请求"""
        for attempt in range(MAX_RETRIES):
            try:
                response = self.session.get(url, params=params, timeout=REQUEST_TIMEOUT)
                response.raise_for_status()
                return response.json()
            except requests.exceptions.Timeout:
                if attempt < MAX_RETRIES - 1:
                    print(f"    [!] 请求超时，正在重试 ({attempt + 1}/{MAX_RETRIES})...")
                    time.sleep(2 ** attempt)
                else:
                    raise
            except requests.exceptions.ConnectionError as e:
                if attempt < MAX_RETRIES - 1:
                    print(f"    [!] 连接错误，正在重试 ({attempt + 1}/{MAX_RETRIES})...")
                    time.sleep(2 ** attempt)
                else:
                    raise
            except Exception as e:
                raise
        return None
    
    def search_anime(self, query: str) -> Optional[dict]:
        """搜索动漫，返回最匹配的中文结果（v2.1.9：遍历所有结果选相似度最高的）"""
        try:
            # 使用 v0 搜索 API
            url = f"{self.base_url}/search/subject/{requests.utils.quote(query)}"
            params = {
                "type": 2,  # 2 = 动画
                "responseGroup": "small",
                "start": 0,
                "max_results": 10
            }
            data = self._make_request(url, params)
            
            if not data:
                return None
            
            results = data.get("list", []) or data.get("items", [])
            if not results:
                return None
            
            # v2.1.9：遍历所有结果，计算相似度，选最匹配的
            best_match = None
            best_similarity = 0.0
            query_lower = query.lower()
            
            def is_special_content(name, original_name):
                """检查是否是外传/OVA/剧场版等特别内容"""
                name_lower = (name or '').lower()
                original_lower = (original_name or '').lower()
                for kw in SPECIAL_CONTENT_KEYWORDS:
                    kw_lower = kw.lower()
                    if kw_lower in name_lower or kw_lower in original_lower:
                        return True
                return False
            
            # 检查搜索词是否包含特别篇关键词
            query_has_special = any(kw.lower() in query_lower for kw in SPECIAL_CONTENT_KEYWORDS)
            
            for r in results:
                r_name_cn = (r.get("name_cn") or "").strip()
                r_name = (r.get("name") or "").strip()
                
                # 过滤特别篇结果（除非用户就是搜特别篇）
                if not query_has_special and is_special_content(r_name_cn, r_name):
                    continue
                
                # 计算相似度：和中文名、原名都比，取最高
                sim_cn = calculate_similarity(query_lower, r_name_cn.lower()) if r_name_cn else 0
                sim_original = calculate_similarity(query_lower, r_name.lower()) if r_name else 0
                sim = max(sim_cn, sim_original)
                
                if sim > best_similarity:
                    best_similarity = sim
                    best_match = r
            
            # 如果没找到合适的，用第一个结果（但后面会有相似度检查）
            if best_match is None:
                best_match = results[0]
                r_name_cn = (best_match.get("name_cn") or "").strip()
                r_name = (best_match.get("name") or "").strip()
                sim_cn = calculate_similarity(query_lower, r_name_cn.lower()) if r_name_cn else 0
                sim_original = calculate_similarity(query_lower, r_name.lower()) if r_name else 0
                best_similarity = max(sim_cn, sim_original)
            
            # v2.3.1：智能阈值判断
            # 如果所有结果相似度都是0，且搜索词没有专属长关键词（短词/通用词容易匹配错），返回None
            # 长罗马音搜索（如Botsuraku）即使和中/日名相似度0，也是正确结果，不返回None
            if best_similarity == 0:
                # 通用停用词，不算专属关键词
                stop_words = {'the', 'series', 'movie', 'special', 'extra', 'part', 'season', 'ova', 'oad', 'movie', 'film', 'and', 'that', 'this', 'with', 'from'}
                query_keywords = [w for w in query_lower.split() if len(w) > 2 and w not in stop_words]
                has_long_keyword = any(len(w) >= 5 for w in query_keywords)
                if not has_long_keyword:
                    return None
            
            # 取最佳结果的详细信息
            subject_id = best_match.get("id")
            if subject_id:
                return self.get_subject_details(subject_id)
            
            # 如果没有 id，直接用搜索结果
            return {
                "id": best_match.get("id"),
                "name": best_match.get("name_cn") or best_match.get("name", ""),
                "original_name": best_match.get("name", ""),
                "year": best_match.get("air_date", "")[:4] if best_match.get("air_date") else None,
                "summary": best_match.get("summary", "")
            }
            
        except Exception as e:
            print(f"    [!] Bangumi 搜索出错: {e}")
            return None

    
    def get_subject_details(self, subject_id: int) -> Optional[dict]:
        """获取动漫详情"""
        try:
            url = f"{self.base_url}/v0/subjects/{subject_id}"
            data = self._make_request(url)
            if not data:
                return None
            
            name_cn = data.get("name_cn", "")
            name = data.get("name", "")
            air_date = data.get("air_date", "")
            
            # 提取年份
            year = None
            if air_date:
                match = re.match(r'(\d{4})', air_date)
                if match:
                    year = int(match.group(1))
            
            # 优先用中文名
            display_name = name_cn if name_cn else name
            
            return {
                "id": subject_id,
                "name": display_name,
                "original_name": name,
                "name_cn": name_cn,
                "air_date": air_date,
                "year": year,
                "summary": data.get("summary", "")
            }
        except Exception as e:
            print(f"    [!] 获取详情出错: {e}")
            return None


class AnimeRenamer:
    """动漫重命名器"""
    
    def __init__(self, root_path: str, tmdb_api_key: str = "", dry_run: bool = True, 
                 proxy: str = "", data_source: str = "auto", 
                 include_year: bool = True, special_naming: str = "s00e01"):
        self.root_path = Path(root_path)
        self.dry_run = dry_run
        self.data_source = data_source
        self.include_year = include_year
        self.special_naming = special_naming
        
        # 初始化客户端
        self.tmdb_client = None
        if tmdb_api_key and tmdb_api_key != "你的TMDB_API_KEY":
            self.tmdb_client = TMDBClient(tmdb_api_key, proxy)
        elif self.data_source in ("tmdb", "auto"):
            # TMDB key 无效时自动切换为 Bangumi
            if self.data_source == "tmdb":
                print("⚠️  TMDB API Key 无效，自动切换为 Bangumi 数据源")
            self.data_source = "bangumi"
        
        self.bangumi_client = BangumiClient(proxy)
        
        # 缓存搜索结果
        self._name_cache: Dict[str, dict] = {}
        
        # 统计
        self.folders_processed = 0
        self.folders_skipped = 0
        self.folders_renamed = 0
        self.files_renamed = 0
        self.errors = 0
        self.merged_folders = 0
        
        # 变更日志
        self.changes: List[str] = []
    
    def search_chinese_name(self, original_name: str) -> Optional[dict]:
        """从动漫数据库搜索中文名称"""
        # 先查缓存
        cache_key = original_name.strip().lower()
        if cache_key in self._name_cache:
            return self._name_cache[cache_key]
        
        # 清理名称用于搜索
        search_name = clean_name(original_name)
        

        # v2.1.7.2: 如果名称包含剧场版/章节/特别篇系列名称，截取前面的正片名称搜索
        # 例如 "Princess Principal Crown Handler 04" -> "Princess Principal"
        series_keywords = [
            'Crown Handler', 'Chapter', 'Extra Part', 'EXTRA PART',
            'Movie', 'Film', '剧场版', '劇場版', '特别篇', '特別篇',
            'OVA', 'OAD', 'SP', 'Special', '番外', '外傳',
            '第1章', '第2章', '第3章', '第4章', '第5章', '第6章'
        ]
        for kw in series_keywords:
            kw_pattern = re.compile(re.escape(kw), re.IGNORECASE)
            match = kw_pattern.search(search_name)
            if match:
                # 截取关键词前面的部分作为正片名称
                main_name = search_name[:match.start()].strip()
                if len(main_name) >= 3:  # 确保截取后名称足够长
                    search_name = main_name
                    break
        if not search_name or search_name == "未命名动漫":
            return None
        
        result = None
        source = ""
        used_short_keyword = False
        
        # v2.1.7 修复：短搜索词检测，区分中英文
        # 中文每个字都是有意义的，2个中文字就可以搜索；英文需要至少3个字符
        def count_chinese_characters(s):
            return len(re.findall(r'[一-鿿]', s))
        
        name_len = len(search_name.strip())
        chinese_count = count_chinese_characters(search_name)
        is_chinese_name = chinese_count >= 2  # 包含2个以上中文字就算中文名
        is_very_short_keyword = False
        
        if is_chinese_name:
            # 中文名：<2个字符才跳过
            if name_len < 2:
                is_very_short_keyword = True
        else:
            # 英文/罗马音名：<3个字符跳过
            if name_len < 3:
                is_very_short_keyword = True
        
        # v2.1.7: 极短名称（非中文<=4字符，中文<2字符）强制低置信度，避免MAO这种3字母匹配到完全不相关的结果
        is_short_keyword = (not is_chinese_name and name_len <= 4) or (is_chinese_name and name_len < 2)
        
        # 太短的关键词直接不搜索，避免严重匹配错误
        if is_very_short_keyword:
            print(f"    [!] 搜索词过短 ({name_len}字符)，跳过自动匹配")
            self._name_cache[cache_key] = None
            return None
        
        # 根据数据源优先级搜索
        sources_to_try = []
        if self.data_source == "tmdb":
            sources_to_try = ["tmdb"]
        elif self.data_source == "bangumi":
            sources_to_try = ["bangumi"]
        else:  # auto
            # 优先 TMDB（Plex/Emby/Jellyfin/飞牛 默认刮削源），失败再试 Bangumi
            sources_to_try = ["tmdb", "bangumi"]
        
        result = None
        source = ""
        result_tmdb = None
        result_bangumi = None
        
        for src in sources_to_try:
            if src == "tmdb":
                if self.tmdb_client:
                    print(f"    正在尝试 TMDB 搜索...")
                    result_tmdb = self.tmdb_client.search_tv(search_name)
                    if result_tmdb:
                        source = "TMDB"
                        if self.data_source != "auto":
                            result = result_tmdb
                            break
                else:
                    continue
            elif src == "bangumi":
                print(f"    正在尝试 Bangumi 搜索...")
                result_bangumi = self.bangumi_client.search_anime(search_name)
                if result_bangumi:
                    if not result:
                        source = "Bangumi"
                        result = result_bangumi
                    if self.data_source != "auto":
                        break
            
            # 请求间隔
            time.sleep(REQUEST_DELAY)
        
        # auto 模式：双源比较，选更优的（用原始名称相似度比较）
        if self.data_source == "auto" and result_tmdb and result_bangumi:
            # 计算两个结果与搜索词的名称相似度
            tmdb_orig = result_tmdb.get("original_name", "") or result_tmdb.get("name", "")
            bgm_orig = result_bangumi.get("original_name", "") or result_bangumi.get("name", "")
            tmdb_sim = calculate_similarity(search_name, tmdb_orig) if tmdb_orig else 0
            bgm_sim = calculate_similarity(search_name, bgm_orig) if bgm_orig else 0
            # 优先 TMDB（Plex/Emby/Jellyfin 标准刮削源），Bangumi 显著更优时替换
            if bgm_sim > tmdb_sim + 0.2:
                result = result_bangumi
                source = "Bangumi"
            else:
                result = result_tmdb
                source = "TMDB"
        elif self.data_source == "auto":
            result = result_tmdb or result_bangumi
            if result_bangumi and not result_tmdb:
                source = "Bangumi"
        
        # 如果没找到，试试更短的关键词（但有长度限制，防止匹配错误）
        if not result and not is_very_short_keyword:
            # 取前两个单词
            short_name = ' '.join(search_name.split()[:2])
            # v2.1.7 提高短关键词长度要求，防止短词匹配错误
            MIN_SHORT_KEYWORD_LENGTH_V2 = 8  # 原来的 MIN_SHORT_KEYWORD_LENGTH 是 10，这里更严格
            if short_name != search_name and len(short_name) >= MIN_SHORT_KEYWORD_LENGTH_V2:
                print(f"    尝试短关键词搜索: {short_name}")
                used_short_keyword = True
                for src in sources_to_try:
                    if src == "tmdb" and self.tmdb_client:
                        result = self.tmdb_client.search_tv(short_name)
                        if result:
                            source = "TMDB"
                            break
                    elif src == "bangumi":
                        result = self.bangumi_client.search_anime(short_name)
                        if result:
                            source = "Bangumi"
                            break
        
        # 相似度校验和置信度评估
        if result:
            result_name = result.get("name", "")
            result_original_name = result.get("original_name", "")
            
            # 1. 中文名相似度（如果搜索词是中文）
            chinese_similarity = calculate_similarity(search_name, result_name)
            
            # 2. 原名相似度（更准确，特别是对于日文/罗马音名称）
            original_similarity = 0.0
            if result_original_name:
                original_similarity = calculate_similarity(search_name, result_original_name)
            
            # 3. 取较高的那个相似度作为最终相似度
            # （中文名称和中文名比，日文/罗马音和原名比）
            similarity = max(chinese_similarity, original_similarity)
            
            # 4. 检测搜索词的类型（用于优化置信度评估）
            # 判断搜索词是否是罗马音/英文（纯英文，没有中文和日文）
            is_romaji_search = bool(re.match(r'^[a-zA-Z0-9\s\-_.,\']+$', search_name))
            # 判断原名是否是日文（包含平假名/片假名/汉字）
            is_japanese_original = bool(re.search(r'[\u3040-\u309f\u30a0-\u30ff]', result_original_name)) if result_original_name else False
            
            # 5. 置信度评估（v1.9 优化）
            confidence = "high"  # 高置信度
            confidence_reasons = []
            
            # 如果使用了短关键词，降低置信度
            if used_short_keyword:
                confidence = "low"
                confidence_reasons.append("使用了短关键词搜索")
            
            # v2.1.7 新增：短搜索词（<5字符）自动标记为低置信度
            if is_short_keyword and not used_short_keyword:
                confidence = "low"
                confidence_reasons.append(f"搜索词过短 ({len(search_name.strip())}字符)，匹配结果可能不准确")
            
            # 罗马音 vs 日文原名的特殊处理
            # 罗马音和日文原名字符集完全不同，相似度天然为0%，这是正常的
            # 不应该仅仅因为相似度低就降低置信度
            if is_romaji_search and is_japanese_original:
                # 罗马音搜索 + 日文原名：相似度低是正常的
                # 只要是完整关键词搜索的第一个结果，就给予 medium 置信度
                if not used_short_keyword:
                    if confidence == "high":
                        confidence = "medium"  # 不是 high，但也不是 low
                    confidence_reasons.append("罗马音名称，相似度仅供参考")
            # v2.3.1：短罗马音搜索词（有效长度≤4）容易匹配错，标记为低置信度
            if is_romaji_search:
                # 去掉短虚词（the/a/an/of/in/on等），计算有效关键词长度
                keywords = [w for w in search_name.split() if len(w) > 2]
                effective_length = sum(len(w) for w in keywords)
                if effective_length <= 4:
                    confidence = "low"
                    confidence_reasons.append(f"短罗马音搜索词（有效长度{effective_length}字符），匹配结果可能不准确")
            else:
                # 普通情况：如果相似度太低，降低置信度
                if similarity < ORIGINAL_NAME_SIMILARITY_THRESHOLD:
                    if confidence != "low":
                        confidence = "medium"
                    confidence_reasons.append(f"名称相似度较低 ({similarity:.0%})")
                
                # 如果中文名和原名都不匹配，降低置信度
                if chinese_similarity < 0.2 and original_similarity < 0.2:
                    if confidence != "low":
                        confidence = "low"
                    confidence_reasons.append("原名和中文名都不匹配")
            
            # v3.2.0：绝对相似度阈值，完全不相关的结果直接跳过
            if similarity < 0.2:
                if not (is_romaji_search and is_japanese_original):
                    print(f"    ⚠️  匹配相似度过低 ({similarity:.0%})，跳过自动重命名，保留原名")
                    print(f"        搜索词: {search_name}")
                    print(f"        候选结果: {result_name}")
                    self._name_cache[cache_key] = None
                    return None
                # romaji+JP：similarity天然为0%，不设底线，信任其他过滤机制

            # API返回的中文名与搜索词相似度过低时也跳过（仅中文搜索词）
            if is_chinese_name and chinese_similarity < 0.1:
                print(f"    ⚠️  中文名相似度过低 ({chinese_similarity:.0%})，可能误匹配，跳过")
                print(f"        搜索词: {search_name}")
                print(f"        API中文名: {result_name}")
                self._name_cache[cache_key] = None
                return None
            
            # 英文搜索词时检查original_name相似度
            if not is_chinese_name and result_original_name and original_similarity < 0.10 and not (is_romaji_search and is_japanese_original):
                print(f"    ⚠️  原名相似度过低 ({original_similarity:.0%})，可能误匹配，跳过")
                print(f"        搜索词: {search_name}")
                print(f"        API原名: {result_original_name}")
                self._name_cache[cache_key] = None
                return None

            # v3.4.0：跨语言零字符过滤（防 GAP→超能迷你队 类误匹配）
            # 搜索词纯英文，API返回纯中文，且无任何共同字符 → 几乎一定是误匹配
            if result_name and search_name and not is_chinese_name:
                has_cjk_result = bool(re.search(r'[\u4e00-\u9fff]', result_name))
                if has_cjk_result and original_similarity < 0.3 and not (is_romaji_search and is_japanese_original):
                    common = set(search_name.lower()) & set(result_name.lower())
                    if not common:
                        print(f"    ⚠️  跨语言零字符匹配，可能误匹配，跳过")
                        print(f"        搜索词: {search_name}")
                        print(f"        API结果: {result_name}")
                        self._name_cache[cache_key] = None
                        return None

            # v2.1.7 修改：低置信度匹配直接跳过，不自动重命名，保留原名
            if confidence == "low":
                print(f"    ⚠️  低置信度匹配，跳过自动重命名，保留原名")
                print(f"        搜索词: {search_name}")
                print(f"        候选结果: {result_name}")
                print(f"        原名: {result_original_name}")
                if confidence_reasons:
                    print(f"        原因: {', '.join(confidence_reasons)}")
                self._name_cache[cache_key] = None
                return None
            
            result["source"] = source
            result["similarity"] = similarity
            result["confidence"] = confidence
            result["used_short_keyword"] = used_short_keyword
        
        # 缓存结果
        self._name_cache[cache_key] = result
        return result
    
